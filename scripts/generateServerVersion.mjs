import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from "url";

/**
 * Writes app's version to a TS file so ti can be read at runtme server-side
 */

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const packageJsonPath = path.join(__dirname, "..", "package.json");
const versionFilePath = path.join(__dirname, "..", "src_back", "utils", "AppVersion.ts");

const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, "utf8"));
//Server parses the major version, an invalid one would make it refuse every data save
if (!/^\d+\./.test(packageJson.version)) {
	throw new Error('Invalid package.json version "' + packageJson.version + '"');
}
const content = `// ========= DO NOT EDIT MANUALLY =========
// Generated by scripts/generateServerVersion.mjs from package.json
export const APP_VERSION = ${JSON.stringify(packageJson.version)};
`;

//Only write if changed to avoid triggering a useless rebuild.
const current = fs.existsSync(versionFilePath) ? fs.readFileSync(versionFilePath, "utf8") : "";
if (current.replace(/\r/g, "") != content) {
	fs.writeFileSync(versionFilePath, content);
}
